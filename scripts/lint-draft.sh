#!/bin/sh
# POSTING.md 2-4 퇴고 점검표 중 grep 으로 셀 수 있는 항목을 센다. 0 이 목표는 아니고 문장을 다시 볼 자리를 찾는 용도.
#   npm run lint:draft -- drafts/<slug>.md
f="$1"
for p in '죠[.?]' '고,' '며,' '지만,' '면서,' '서,' '아니라' '아닌' '굴리' '뜯어' '걷어' '당겨' '쥐' '짚' '뱉' '조용히' '우아하게' '단순히' '기본적으로' '흥미로운 건' '살펴봅' '따라가 봅' '셋입니다' '둘입니다' '넷입니다' '넷이면' '정체' '지점' '자리' '내려받' '출발합니다' '갈립니다' '해요' '예요' '잖아요' '더라고요' '셈입니다' '\*\*[^*]*[)%]\*\*[가-힣]'; do
  n=$(grep -o -- "$p" "$f" | wc -l)
  [ "$n" -gt 0 ] && echo "$p: $n"
done
echo "lines: $(wc -l < "$f")"
