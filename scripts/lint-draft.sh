#!/bin/sh
# POSTING.md 2-4 퇴고 점검표 중 grep 으로 셀 수 있는 항목을 센다. 0 이 목표는 아니고 문장을 다시 볼 자리를 찾는 용도.
#   npm run lint:draft -- drafts/<slug>.md
f="$1"
for p in '죠[.?]' '고,' '며,' '지만,' '면서,' '서,' '아니라' '아닌' '굴리' '뜯어' '걷어' '당겨' '쥐' '짚' '뱉' '조용히' '우아하게' '단순히' '기본적으로' '흥미로운 건' '살펴봅' '따라가 봅' '따라갑니다' '따라가겠' '하나씩 보겠' '셋입니다' '둘입니다' '넷입니다' '넷이면' '정체' '지점' '자리' '내려받' '출발합니다' '갈립니다' '[0-9~]편' '가 보입니다' '지 보입니다' '한 개도' '풀립니다' '일이 많습니다' '경우가 많습니다' '경향이 있' '나란히 놓' '해요' '예요' '잖아요' '더라고요' '셈입니다' '^## .* — ' '뒤에 올' '올 법한' '그것 하나' '몫으로 남' '하는 쪽은' '끼워 넣' '달라진 것은' '무엇이었나요' '먼저 알아야' '새 낱말' '읽는 시간' '오늘의 목표' '떠올리기' '소리 내어' '\*\*[^*]*[)%]\*\*[가-힣]'; do
  n=$(grep -o -- "$p" "$f" | wc -l)
  [ "$n" -gt 0 ] && echo "$p: $n"
done
echo "lines: $(wc -l < "$f")"
# 왼쪽 테두리만 색칠한 강조 금지(POSTING 5-2). 화살촉(transparent 와 같이 쓰는 줄)은 제외.
n=$(grep -E 'border-left: *[2-9](\.[0-9])?px solid' "$f" | grep -vc transparent); [ "$n" -gt 0 ] && echo "border-left 색 띠(금지): $n"
